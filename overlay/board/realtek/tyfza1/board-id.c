static int fip_board_id(const void *data)
{
	/* SHA256(BL2) followed by SHA256(BL31), from evidence/stock-boot/. */
	static const unsigned char fingerprints[2][64] = {
		{ /* 2p5g, conf-0 */
			0xb0,0x4b,0x7a,0xba,0xad,0x15,0x2f,0x57,0x08,0xd8,0xaf,0xf2,0x16,0xa0,0x76,0x5b,
			0x5b,0xef,0x4f,0x72,0x6b,0xee,0xda,0x1c,0x5f,0x19,0x93,0x76,0xc8,0x43,0x49,0x34,
			0x1f,0x64,0x44,0xe2,0x24,0x4f,0xd1,0x9a,0xf6,0x55,0x13,0x2a,0xaa,0xa1,0x75,0x8a,
			0x81,0x79,0x8d,0xd5,0xc8,0x51,0xfb,0xe4,0x6e,0x85,0x56,0x7f,0x91,0x5c,0x7d,0xb9,
		},
		{ /* 4ge, conf-1 */
			0xaf,0xfb,0x25,0x47,0xab,0xd0,0x73,0xc1,0x47,0x4e,0x6e,0xb0,0x1e,0x7a,0xb9,0x83,
			0x15,0x65,0xe9,0x8a,0x38,0x4b,0x8b,0x9f,0x92,0x21,0xb2,0x9f,0x4a,0x32,0xa2,0x37,
			0x9f,0xf8,0x91,0xae,0x6a,0x4a,0xd5,0x9c,0x48,0xcc,0x3a,0x5e,0x58,0x2f,0x91,0x6b,
			0x77,0x7a,0x48,0xa8,0xd5,0xa5,0x9e,0x3f,0x22,0xb8,0xb2,0x15,0x67,0xb2,0xb9,0x05,
		},
	};
	struct tyf_fip image;
	unsigned char hash[64];
	unsigned int i;

	if (tyf_parse_fip(data, TYF_FIP_SIZE, &image)) return -ENODEV;
	sha256_csum_wd(image.bl2.data, image.bl2.size, hash, CHUNKSZ_SHA256);
	sha256_csum_wd(image.bl31.data, image.bl31.size, hash + 32, CHUNKSZ_SHA256);
	for (i = 0; i < ARRAY_SIZE(fingerprints); i++)
		if (!memcmp(hash, fingerprints[i], sizeof(hash))) return i;
	return -ENODEV;
}

int tyfza1_board_id(void)
{
	const size_t offsets[] = { TYF_FIP0_OFFSET, TYF_FIP1_OFFSET };
	struct mtd_info *mtd;
	unsigned char *data = NULL;
	size_t done;
	unsigned int i;
	int ret, board = -ENODEV;

	mtd_probe_devices();
	mtd = get_mtd_device_nm("boot");
	if (IS_ERR(mtd)) return -ENODEV;
	if (mtd->size != TYF_BOOT_SIZE) goto out;
	data = malloc_cache_aligned(TYF_FIP_SIZE);
	if (!data) goto out;
	/* BL2/BL31 survive U-Boot updates; either FIP may be recovering an update. */
	for (i = 0; i < ARRAY_SIZE(offsets); i++) {
		ret = mtd_read(mtd, offsets[i], TYF_FIP_SIZE, &done, data);
		if ((ret && ret != -EUCLEAN) || done != TYF_FIP_SIZE) continue;
		board = fip_board_id(data);
		if (board >= 0) break;
	}
out:
	free(data);
	put_mtd_device(mtd);
	return board;
}
